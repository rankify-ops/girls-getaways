/*
 * src/content/site.ts → supabase/seed.sql
 *
 * The 16 packages, 22 destinations, 7 states and 5 styles captured from the
 * live Squarespace site are the portal's starting data. Generating the SQL
 * from the same file the site renders from means the two can't drift, and
 * re-running is safe: every insert is an upsert keyed on the slug.
 *
 * Node reads the .ts directly (type stripping), so there's no build step.
 *
 * Run: node scripts/seed.mjs > supabase/seed.sql
 */
import { packages, destinations, states, STYLES, destBySlug } from "../src/content/site.ts";

const q = (v) =>
  v === null || v === undefined || v === "" ? "null" : `'${String(v).replace(/'/g, "''")}'`;
const n = (v) => (v === null || v === undefined ? "null" : Number(v));
const bool = (v) => (v ? "true" : "false");

const out = [];
out.push("-- Generated by scripts/seed.mjs — do not edit by hand.");
out.push("begin;");

out.push("\n-- states");
states.forEach((s, i) => {
  out.push(
    `insert into states (code, name, short, grouping, position) values (${q(s.code)}, ${q(s.name)}, ${q(
      s.short
    )}, ${q(s.group)}, ${i}) on conflict (code) do update set name = excluded.name, short = excluded.short, grouping = excluded.grouping, position = excluded.position;`
  );
});

out.push("\n-- destinations");
destinations.forEach((d, i) => {
  out.push(
    `insert into destinations (slug, name, state_code, position) values (${q(d.slug)}, ${q(d.name)}, ${q(
      d.state
    )}, ${i}) on conflict (slug) do update set name = excluded.name, state_code = excluded.state_code, position = excluded.position;`
  );
});

out.push("\n-- styles");
const styleIcon = {
  Hens: "ico-hens",
  Classic: "ico-city",
  Luxury: "ico-luxury",
  "Winter Wines": "ico-wine",
  "Girl's Day": "ico-pamper",
};
STYLES.forEach((s, i) => {
  const slug = s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
  out.push(
    `insert into styles (slug, name, icon, position) values (${q(slug)}, ${q(s)}, ${q(
      styleIcon[s] ?? null
    )}, ${i}) on conflict (slug) do update set name = excluded.name, icon = excluded.icon, position = excluded.position;`
  );
});

out.push("\n-- packages");
packages.forEach((p, i) => {
  const destSlug = destBySlug[p.dest]?.slug ?? null;
  // Published: these are all live on the current website today.
  out.push(
    `insert into packages (slug, title, venue, destination_id, area, blurb, price_from, guests_min, guests_max, nights, tag, popular, status, position, legacy_path)
 values (${q(p.slug)}, ${q(p.title)}, ${q(p.venue ?? null)},
   (select id from destinations where slug = ${q(destSlug)}),
   ${q(p.area ?? null)}, ${q(p.blurb ?? null)}, ${n(p.priceFrom ?? null)},
   ${n(p.guests?.[0] ?? null)}, ${n(p.guests?.[1] ?? null)}, ${n(p.nights ?? null)},
   ${q(p.tag ?? null)}, ${bool(p.tag === "Featured")}, 'published', ${i}, ${q(p.path)})
 on conflict (slug) do update set title = excluded.title, venue = excluded.venue,
   destination_id = excluded.destination_id, area = excluded.area, blurb = excluded.blurb,
   price_from = excluded.price_from, guests_min = excluded.guests_min, guests_max = excluded.guests_max,
   nights = excluded.nights, tag = excluded.tag, popular = excluded.popular, position = excluded.position,
   legacy_path = excluded.legacy_path;`
  );
});

out.push("\n-- package styles");
packages.forEach((p) => {
  p.styles.forEach((s) => {
    const slug = s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
    out.push(
      `insert into package_styles (package_id, style_id) select p.id, s.id from packages p, styles s where p.slug = ${q(
        p.slug
      )} and s.slug = ${q(slug)} on conflict do nothing;`
    );
  });
});

out.push("\ncommit;");
process.stdout.write(out.join("\n") + "\n");
